// Object storage drivers (HANDOFF §11). This module has no 'server-only' import and no '@/' imports
// so prisma/seed.ts, which tsx runs outside Next, can use it. App code goes through lib/files/storage.ts.
import { createReadStream } from 'node:fs';
import { mkdir, open, rm, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { Readable } from 'node:stream';
import {
  DeleteObjectCommand,
  GetObjectCommand,
  HeadObjectCommand,
  PutObjectCommand,
  S3Client,
} from '@aws-sdk/client-s3';
import { getSignedUrl } from '@aws-sdk/s3-request-presigner';
import { hmac, safeEqual } from './sign';

export type StoredObject = { body: ReadableStream<Uint8Array>; size: number; contentType: string | null };
export type ObjectInfo = { size: number; contentType: string | null };
export type PresignedPut = { url: string; headers: Record<string, string> };

export interface StorageDriver {
  readonly kind: 's3' | 'local';
  /** A URL the browser can PUT exactly `size` bytes of `contentType` to, valid for 5 minutes. */
  presignPut(key: string, contentType: string, size: number): Promise<PresignedPut>;
  put(key: string, body: Uint8Array, contentType: string): Promise<void>;
  /** The object as a stream, or null when it doesn't exist. */
  get(key: string): Promise<StoredObject | null>;
  head(key: string): Promise<ObjectInfo | null>;
  /** The first `bytes` bytes (for sniffing), or null when the object doesn't exist. */
  readStart(key: string, bytes?: number): Promise<Uint8Array | null>;
  /** Deletes the object; missing objects are not an error. */
  remove(key: string): Promise<void>;
}

export type StorageConfig = {
  bucket: string;
  endpoint: string;
  region: string;
  accessKeyId: string;
  secretAccessKey: string;
  /** Signs local-driver upload URLs (read lazily: only the local driver needs it). */
  localSecret: () => string;
  /** Root folder of the local driver (default `.data/uploads` under the working directory). */
  localRoot?: string;
};

export const PRESIGN_SECONDS = 5 * 60;

const KEY_RE = /^[a-z0-9-]+(\/[A-Za-z0-9][A-Za-z0-9._-]*)+$/;

/** Object keys are generated by the server; anything else (path tricks, odd characters) is refused. */
export function assertKey(key: string): void {
  if (typeof key !== 'string' || key.length > 200 || !KEY_RE.test(key) || key.includes('..')) {
    throw new Error(`Invalid storage key: ${JSON.stringify(key)}`);
  }
}

const blank = (v: string | undefined) => (v ?? '').trim();

/** Storage settings straight from process.env (for scripts that run outside Next, such as the seed). */
export function storageConfigFromProcessEnv(localSecret: () => string): StorageConfig {
  return {
    bucket: blank(process.env.S3_BUCKET),
    endpoint: blank(process.env.S3_ENDPOINT),
    region: blank(process.env.S3_REGION) || 'auto',
    accessKeyId: blank(process.env.S3_ACCESS_KEY_ID),
    secretAccessKey: blank(process.env.S3_SECRET_ACCESS_KEY),
    localSecret,
  };
}

/** S3 when a bucket is configured, otherwise the local-disk driver. */
export function createStorage(config: StorageConfig): StorageDriver {
  return config.bucket ? s3Driver(config) : localDriver(config);
}

/* ------------------------------------------------------------------ S3 / R2 */

const isMissing = (e: unknown) => {
  const err = e as { name?: string; Code?: string; $metadata?: { httpStatusCode?: number } } | null;
  return err?.name === 'NoSuchKey' || err?.name === 'NotFound' || err?.Code === 'NoSuchKey' || err?.$metadata?.httpStatusCode === 404;
};

/** One client for R2, Neon Object Storage and AWS S3 (path-style; Neon supports nothing else). */
export function s3Client(config: StorageConfig): S3Client {
  return new S3Client({
    region: config.region || 'auto',
    ...(config.endpoint ? { endpoint: config.endpoint } : {}),
    forcePathStyle: true,
    credentials:
      config.accessKeyId && config.secretAccessKey
        ? { accessKeyId: config.accessKeyId, secretAccessKey: config.secretAccessKey }
        : undefined,
    // Without this, newer SDKs sign a CRC32 of an empty body into presigned PUT URLs, and R2 and Neon reject the real upload.
    requestChecksumCalculation: 'WHEN_REQUIRED',
    responseChecksumValidation: 'WHEN_REQUIRED',
  });
}

function s3Driver(config: StorageConfig): StorageDriver {
  const client = s3Client(config);
  const Bucket = config.bucket;

  return {
    kind: 's3',

    async presignPut(key, contentType, size) {
      assertKey(key);
      const url = await getSignedUrl(client, new PutObjectCommand({ Bucket, Key: key, ContentType: contentType, ContentLength: size }), {
        expiresIn: PRESIGN_SECONDS,
        // Signing both headers caps the upload at exactly the size and type the server approved.
        signableHeaders: new Set(['content-type', 'content-length']),
      });
      return { url, headers: { 'Content-Type': contentType } };
    },

    async put(key, body, contentType) {
      assertKey(key);
      await client.send(new PutObjectCommand({ Bucket, Key: key, Body: body, ContentType: contentType, ContentLength: body.byteLength }));
    },

    async get(key) {
      assertKey(key);
      try {
        const res = await client.send(new GetObjectCommand({ Bucket, Key: key }));
        if (!res.Body) return null;
        return {
          body: res.Body.transformToWebStream() as ReadableStream<Uint8Array>,
          size: Number(res.ContentLength ?? 0),
          contentType: res.ContentType ?? null,
        };
      } catch (e) {
        if (isMissing(e)) return null;
        throw e;
      }
    },

    async head(key) {
      assertKey(key);
      try {
        const res = await client.send(new HeadObjectCommand({ Bucket, Key: key }));
        return { size: Number(res.ContentLength ?? 0), contentType: res.ContentType ?? null };
      } catch (e) {
        if (isMissing(e)) return null;
        throw e;
      }
    },

    async readStart(key, bytes = 16) {
      assertKey(key);
      try {
        const res = await client.send(new GetObjectCommand({ Bucket, Key: key, Range: `bytes=0-${Math.max(1, bytes) - 1}` }));
        if (!res.Body) return new Uint8Array(0);
        const all = await res.Body.transformToByteArray();
        return all.subarray(0, bytes);
      } catch (e) {
        if (isMissing(e)) return null;
        // An empty object can't satisfy a byte range.
        if ((e as { name?: string; $metadata?: { httpStatusCode?: number } })?.name === 'InvalidRange' || (e as { $metadata?: { httpStatusCode?: number } })?.$metadata?.httpStatusCode === 416) {
          return new Uint8Array(0);
        }
        throw e;
      }
    },

    async remove(key) {
      assertKey(key);
      await client.send(new DeleteObjectCommand({ Bucket, Key: key }));
    },
  };
}

/* --------------------------------------------------------------- Local disk */

const LOCAL_PUT_PATH = '/api/uploads/local';

const localPutPayload = (key: string, contentType: string, size: number, exp: number) =>
  `cleargate-local-put\n${key}\n${contentType}\n${size}\n${exp}`;

export type LocalPutGrant = { key: string; contentType: string; size: number };

/** Checks a local-driver upload URL's query string. Returns null when it is forged or expired. */
export function verifyLocalPutUrl(params: URLSearchParams, secret: string): LocalPutGrant | null {
  const key = params.get('key') ?? '';
  const contentType = params.get('type') ?? '';
  const size = Number(params.get('size'));
  const exp = Number(params.get('exp'));
  const sig = params.get('sig') ?? '';
  if (!key || !contentType || !Number.isSafeInteger(size) || size < 1 || !Number.isSafeInteger(exp)) return null;
  if (!safeEqual(sig, hmac(secret, localPutPayload(key, contentType, size, exp)))) return null;
  if (exp < Date.now()) return null;
  try {
    assertKey(key);
  } catch {
    return null;
  }
  return { key, contentType, size };
}

function localDriver(config: StorageConfig): StorageDriver {
  const root = config.localRoot ?? path.join(/* turbopackIgnore: true */ process.cwd(), '.data', 'uploads');
  const fileFor = (key: string) => {
    assertKey(key);
    const full = path.resolve(root, ...key.split('/'));
    if (!full.startsWith(path.resolve(root) + path.sep)) throw new Error(`Invalid storage key: ${JSON.stringify(key)}`);
    return full;
  };
  const statOrNull = async (file: string) => {
    try {
      const s = await stat(file);
      return s.isFile() ? s : null;
    } catch (e) {
      if ((e as NodeJS.ErrnoException).code === 'ENOENT') return null;
      throw e;
    }
  };

  return {
    kind: 'local',

    async presignPut(key, contentType, size) {
      assertKey(key);
      const exp = Date.now() + PRESIGN_SECONDS * 1000;
      const sig = hmac(config.localSecret(), localPutPayload(key, contentType, size, exp));
      const q = new URLSearchParams({ key, type: contentType, size: String(size), exp: String(exp), sig });
      return { url: `${LOCAL_PUT_PATH}?${q.toString()}`, headers: { 'Content-Type': contentType } };
    },

    async put(key, body) {
      const file = fileFor(key);
      await mkdir(path.dirname(file), { recursive: true });
      await writeFile(file, body);
    },

    async get(key) {
      const file = fileFor(key);
      const s = await statOrNull(file);
      if (!s) return null;
      const body = Readable.toWeb(createReadStream(file)) as unknown as ReadableStream<Uint8Array>;
      return { body, size: s.size, contentType: null };
    },

    async head(key) {
      const s = await statOrNull(fileFor(key));
      return s ? { size: s.size, contentType: null } : null;
    },

    async readStart(key, bytes = 16) {
      const file = fileFor(key);
      if (!(await statOrNull(file))) return null;
      const handle = await open(file, 'r');
      try {
        const buf = Buffer.alloc(Math.max(0, bytes));
        const { bytesRead } = await handle.read(buf, 0, buf.length, 0);
        return new Uint8Array(buf.subarray(0, bytesRead));
      } finally {
        await handle.close();
      }
    },

    async remove(key) {
      await rm(fileFor(key), { force: true });
    },
  };
}
